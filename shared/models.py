"""
shared/models.py — Shared Pydantic Models V5.1
All domain models used across modules. Single source of truth.

V5.1 additions:
  - LLM Structured Output models (HookOutput, CreativeOutput, BrandStrategyOutput)
  - AdsDecision model for kill-switch engine
  - ProductEvaluation model for DecisionEngine
"""
from pydantic import BaseModel, Field
from typing import Optional, List, Literal
from datetime import datetime


class Tenant(BaseModel):
    id: Optional[str] = None
    name: str
    billing_plan: str = "starter"
    llm_quota: dict = Field(default_factory=lambda: {"monthly_usd_limit": 100})
    settings: dict = Field(default_factory=dict)


class Opportunity(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    name: str
    niche: str
    source: str = "oracle_v4"
    score: float = 0.0
    score_breakdown: dict = Field(default_factory=dict)
    viral_score: float = 50.0
    saturation_score: float = 0.0
    status: str = "detected"
    fail_fast_spend_usd: float = 0.0
    raw_data: dict = Field(default_factory=dict)


class Campaign(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    opportunity_id: str
    platform: str                  # tiktok | meta | google | amazon | mercadolibre
    external_campaign_id: Optional[str] = None
    budget_usd: float
    spend_usd: float = 0.0
    revenue_usd: float = 0.0
    roas: Optional[float] = None
    impressions: int = 0
    clicks: int = 0
    conversions: int = 0
    ctr: Optional[float] = None
    cpa: Optional[float] = None
    status: str = "active"         # active | paused | killed | completed
    started_at: Optional[datetime] = None
    ended_at: Optional[datetime] = None


class Hook(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    hook_text: str
    category: str                  # fear|curiosity|scarcity|transformation|social_proof|identity|savings
    niche: Optional[str] = None
    avg_ctr: Optional[float] = None
    test_count: int = 0
    winning_count: int = 0
    metadata: dict = Field(default_factory=dict)


class Brand(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    opportunity_id: str
    name: str
    strategy: dict = Field(default_factory=dict)
    visual_identity: dict = Field(default_factory=dict)
    store_url: Optional[str] = None
    status: str = "pending"        # pending | approved | live


class Product(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    brand_id: str
    name: str
    sku: Optional[str] = None
    price_usd: Optional[float] = None
    cogs_usd: Optional[float] = None
    margin_pct: Optional[float] = None
    description: Optional[str] = None
    images: list = Field(default_factory=list)
    status: str = "draft"


class SaturationLog(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    campaign_id: str
    delta_cpm: float
    new_competitors: int
    delta_ctr: float
    saturation_score: float
    hazard_prob: float
    action_taken: str


class AllocationRun(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    total_budget_usd: float
    allocations: dict              # {campaign_id: budget_usd}
    product_stats: dict = Field(default_factory=dict)
    rationale: str = ""


class DecisionLog(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    entity_type: str               # opportunity | campaign | brand | niche
    entity_id: Optional[str] = None
    action: str                    # kill | approve | scale | hold | alert
    trigger: str = "auto"          # auto | human_gate | timeout
    reason: str = ""
    data: dict = Field(default_factory=dict)


class NicheProfile(BaseModel):
    id: Optional[str] = None
    tenant_id: str
    anchor_opportunity_id: str
    niche_name: str
    anchor_product: str
    complementary_products: list = Field(default_factory=list)
    consolidated_brand_id: Optional[str] = None
    swarm_status: str = "in_progress"  # in_progress | dominated | saturating
    combined_roas: Optional[float] = None



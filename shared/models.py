class AdsDecision(BaseModel):
    """Decision output from AdsDecisionEngine kill-switch."""
    action: Literal["SCALE", "HOLD", "KILL"]
    reason: str = Field(..., max_length=300)
    roas: float = Field(..., ge=0.0)
    spend_usd: float = Field(..., ge=0.0)
    revenue_usd: float = Field(..., ge=0.0)
    budget_change_pct: float  # +20 = scale 20%, 0 = hold, -100 = kill
    campaign_id: str = Field(default="", max_length=64)
    alert_sent: bool = False
    decided_at: Optional[datetime] = None


class ProductEvaluation(BaseModel):
    """Evaluation output from core DecisionEngine."""
    decision: Literal["launch_test", "reject", "manual_review"]
    reason: str = Field(default="", max_length=300)
    score: float = Field(..., ge=0.0, le=100.0)
    budget_usd: float = Field(default=0.0, ge=0.0)
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    product_id: str = Field(default="", max_length=64)
    product_name: str = Field(default="", max_length=200)


class OrchestratorCycleResult(BaseModel):
    """Result of a full autonomous orchestration cycle."""
    cycle_id: str = Field(..., max_length=64)
    tenant_id: str = Field(..., max_length=64)
    niches_processed: int = 0
    signals_found: int = 0
    products_scored: int = 0
    products_approved: int = 0
    products_rejected: int = 0
    creative_hooks_generated: int = 0
    ads_decisions: List[AdsDecision] = Field(default_factory=list)
    total_budget_allocated_usd: float = 0.0
    duration_seconds: float = 0.0
    errors: List[str] = Field(default_factory=list)

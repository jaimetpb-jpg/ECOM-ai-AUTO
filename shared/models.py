class HookOutput(BaseModel):
    """Single TikTok/Meta hook generated by Creative Engine."""
    hook_type: Literal["fear", "transformation", "social_proof", "curiosity", "urgency"]
    hook_text: str = Field(..., max_length=150, description="Hook text <5 seconds")
    script: str = Field(..., max_length=1500, description="Full 30s TikTok script")
    cta: str = Field(..., max_length=100, description="Call to action text")
    estimated_ctr: float = Field(..., ge=0.0, le=1.0, description="Estimated CTR 0-1")
    pain_point_addressed: str = Field(default="", max_length=200)


class CreativeOutput(BaseModel):
    """Structured output from Creative Intelligence Engine."""
    hooks: List[HookOutput] = Field(..., min_length=1, max_length=5)
    product_positioning: str = Field(default="", max_length=300)
    target_audience: str = Field(default="", max_length=200)


class BrandStrategyOutput(BaseModel):
    """Structured brand strategy from BrandCreator."""
    name: str = Field(..., max_length=30)
    tagline: str = Field(..., max_length=80)
    values: List[str] = Field(..., min_length=3, max_length=3)
    voice: str = Field(..., max_length=100)
    positioning: str = Field(..., max_length=300)
    color_palette: List[str] = Field(default_factory=list, max_length=5)
    target_demo: str = Field(default="", max_length=200)


class DiscoverySignal(BaseModel):
    """Product trend signal from Discovery Engine."""
    product_name: str = Field(..., max_length=200)
    niche: str = Field(..., max_length=100)
    trend_source: Literal["tiktok", "amazon", "google_trends", "meta_library"]
    viral_score: float = Field(..., ge=0.0, le=100.0)
    estimated_demand: float = Field(..., ge=0.0, le=100.0)
    competition_level: Literal["low", "moderate", "high", "saturated"]
    pain_points: List[str] = Field(default_factory=list, max_length=5)
    raw_data: dict = Field(default_factory=dict)


